/* Parity fixtures for the phase 2 endpoints (/map, /landing-window, /dsn, /mission-design, /mission-design/atlas),
   dumped from the original in-browser JS engine. Kept apart from make_golden.js so golden.json (made on arm64, where
   V8's Math.log differs in the last bit) is not regenerated by accident.

   The map, Mission Rescue (now Landing window) and the opportunity atlas lived inside src/app.js and were not exported,
   so this script rebuilds them from Ana.verdict, Ana.designFrontier, Terrain.elev and Eng.discFrac with main's loops,
   copied line for line from src/app.js at afd9e78 (castPolar, buildPolar, computeRescue, drawLab, drawAtlas).

   Run from a checkout of afd9e78, which still has the JS engine:
       git worktree add /tmp/ls-js afd9e78 && mkdir -p /tmp/ls-js/backend/tools
       cp backend/tools/make_golden_phase2.js /tmp/ls-js/backend/tools/
       cd /tmp/ls-js && npm ci && node backend/tools/make_golden_phase2.js
   then copy /tmp/ls-js/backend/tests/fixtures/golden_phase2.json and golden_map.bin.gz back. */
global.Eng = require('../../src/engine.js'); global.Terrain = require('../../src/terrain.js');
const Ana = require('../../src/analysis.js'), data = require('../../build/data.json'), fs = require('fs'), path = require('path'), zlib = require('zlib');
const arr = a => Array.from(a, v => (Number.isFinite(v) ? v : (v > 0 ? 'Infinity' : v < 0 ? '-Infinity' : 'NaN')));
const { RM, D2R, R2D } = Eng;

(async () => {
  await Terrain.load(data);
  Terrain.setFocus(-70, 0);               // no fine patch: the map uses the 400 m polar raster only, as in main
  const out = { arch: process.arch, node: process.version };
  // 75 days of hourly Moon-fixed Sun and Earth vectors from 2026-12-01T00:00Z
  const T0 = Date.UTC(2026, 11, 1), N = 75 * 24, tab = Eng.makeTable(T0, 3600e3, N);
  out.table = { t0_ms: T0, step_ms: 3600e3, n: N, a: arr(tab.a) };
  const ids = ['shack', 'ridge', 'gerl', 'ce7', 'mala', 'viper', 'im2', 'im1', 'pole'];
  const ser = {};
  for (const id of ids) { const q = Terrain.profiles.sites[id]; ser[id] = Ana.seriesAt({ id, lat: q.lat, lon: q.lon }, 2, Terrain.profileMask(id, 2), tab, 0, N); }
  const base = { days: 10, peakW: 400, loadSun: 180, loadDark: 60, capWh: 2000, minSoc: 0.2, tracking: true, needEarth: true, maxGapH: 12, margin: 0.3, chargeEff: 0.9, fault: { kind: 'none', day: 3 }, safe: false, autonomyH: 6 };

  // 1. Sunlight and Earth-view map: main's buildPolar and castPolar (src/app.js), 400 px, at three table hours
  const PS = 400, CAP = -80, RHO = 2 * RM * Math.tan((90 + CAP) / 2 * D2R), PXKM = 2 * RHO / PS;
  const pH = new Float32Array(PS * PS), pSL = new Float32Array(PS * PS), pCL = new Float32Array(PS * PS), pSO = new Float32Array(PS * PS), pCO = new Float32Array(PS * PS), pIn = new Uint8Array(PS * PS), pHill = new Float32Array(PS * PS);
  const STEPS = []; for (let d = 1; d <= 8; d++) STEPS.push(d); for (let d = 9; d < 190; d *= 1.12) STEPS.push(d);
  for (let y = 0; y < PS; y++) for (let x = 0; x < PS; x++) {
    const i = y * PS + x, Xk = (x + 0.5 - PS / 2) * PXKM, Yk = (PS / 2 - (y + 0.5)) * PXKM, rho = Math.hypot(Xk, Yk);
    const lat = -90 + 2 * Math.atan(rho / (2 * RM)) * R2D, lon = Math.atan2(Xk, Yk);
    pH[i] = Terrain.elev(lat, lon * R2D); pSL[i] = Math.sin(lat * D2R); pCL[i] = Math.cos(lat * D2R); pSO[i] = Math.sin(lon); pCO[i] = Math.cos(lon); pIn[i] = rho <= RHO ? 1 : 0;
  }
  for (let y = 1; y < PS - 1; y++) for (let x = 1; x < PS - 1; x++) {
    const i = y * PS + x, gx = (pH[i + 1] - pH[i - 1]) / (2 * PXKM * 1000), gy = (pH[i + PS] - pH[i - PS]) / (2 * PXKM * 1000);
    pHill[i] = Math.max(0, Math.min(1, 0.5 - 1.8 * (gx + gy)));
  }
  function castPolar(vec, finite, rad, pFrac, pInc) {
    let ux = 0, uy = 0, uz = 0;
    if (!finite) { const L = Math.hypot(vec[0], vec[1], vec[2]); ux = vec[0] / L; uy = vec[1] / L; uz = vec[2] / L; }
    for (let i = 0; i < PS * PS; i++) {
      if (!pIn[i]) continue;
      const sl = pSL[i], cl = pCL[i], so = pSO[i], co = pCO[i], nx = cl * co, ny = cl * so, nz = sl;
      if (finite) { const vx = vec[0] - RM * nx, vy = vec[1] - RM * ny, vz = vec[2] - RM * nz, L = Math.hypot(vx, vy, vz); ux = vx / L; uy = vy / L; uz = vz / L; }
      const el = Math.asin(ux * nx + uy * ny + uz * nz) * R2D;
      if (el < -rad - 7) { pFrac[i] = 0; pInc[i] = 0; continue; }
      const sN = -ux * sl * co - uy * sl * so + uz * cl, sE = -ux * so + uy * co;
      let dx = sN * so + sE * co, dy = -(sN * co - sE * so); const L2 = Math.hypot(dx, dy) || 1; dx /= L2; dy /= L2;
      const x = i % PS, y = (i / PS) | 0, h1 = pH[i], tanTop = Math.tan((el + rad) * D2R); let mt = -0.15;
      for (let k = 0; k < STEPS.length; k++) {
        const d = STEPS[k], xx = Math.round(x + dx * d), yy = Math.round(y + dy * d); if (xx < 0 || yy < 0 || xx >= PS || yy >= PS) break;
        const dk = d * PXKM, tA = (pH[yy * PS + xx] - h1) / (dk * 1000) - dk / (2 * RM); if (tA > mt) { mt = tA; if (mt > tanTop) break; }
      }
      pFrac[i] = Eng.discFrac(el, rad, Math.atan(mt) * R2D);
      const xa = Math.max(0, Math.min(PS - 1, Math.round(x + dx * 1.5))), ya = Math.max(0, Math.min(PS - 1, Math.round(y + dy * 1.5))), xb = Math.max(0, Math.min(PS - 1, Math.round(x - dx * 1.5))), yb = Math.max(0, Math.min(PS - 1, Math.round(y - dy * 1.5)));
      const gsl = (pH[ya * PS + xa] - pH[yb * PS + xb]) / (3 * PXKM * 1000);
      pInc[i] = Math.max(0, Math.sin((el + Math.atan(gsl) * R2D) * D2R));
    }
  }
  const mapHours = [0, 222, 594], bins = [];
  const q16 = a => { const u = new Uint16Array(a.length); for (let i = 0; i < a.length; i++) u[i] = Math.round(Math.max(0, Math.min(1, a[i])) * 65535); return Buffer.from(u.buffer); };
  for (const hh of mapHours) {
    const s = Array.from(tab.a.slice(hh * 6, hh * 6 + 3)), e = Array.from(tab.a.slice(hh * 6 + 3, hh * 6 + 6));
    const sf = new Float32Array(PS * PS), si = new Float32Array(PS * PS), ef = new Float32Array(PS * PS), ei = new Float32Array(PS * PS);
    castPolar(s, false, 0.266, sf, si); castPolar(e, true, 0.95, ef, ei);
    bins.push(q16(sf), q16(si), q16(ef));
  }
  bins.push(q16(pHill), q16(pIn));
  out.map = { size: PS, hours: mapHours, grids: 'per hour: sun visible share, sun incidence, earth visible share (uint16 / 65535, row-major); then hillshade, inside mask',
              file: 'golden_map.bin.gz', elev_sample: [0, 20100, 80200, 159999].map(i => ({ i, h: pH[i] })) };

  // 2. Landing window: main's computeRescue (src/app.js) over the nine polar sites, three plans
  out.landing = [];
  for (const [plan, iP, slip, flex, over] of [['mala', 24, 14, 21, {}], ['shack', 100, 0, 21, { capWh: 1500 }], ['viper', 48, 7, 10, { maxGapH: 48, tracking: false }]]) {
    const cfg = Object.assign({}, base, over), iS = iP + slip * 24, pse = ser[plan];
    const b = Ana.verdict(pse, iP, cfg), sl = Ana.verdict(pse, iS, cfg);
    const alts = ids.map(id => {
      const se = ser[id]; let best = null;
      for (let i = iS; i <= iS + flex * 24; i += 6) { const v = Ana.verdict(se, i, cfg); if (!best || v.state > best.v.state) best = { v, i }; if (v.state === 2) break; }
      let days = 0; for (let d = 0; d <= flex; d++) if (Ana.verdict(se, iS + d * 24, cfg).state > 0) days++;
      const st6 = []; for (let i = iS; i <= iS + flex * 24; i += 6) st6.push(Ana.verdict(se, i, cfg).state);
      return { id, state: best.v.state, i: best.i, minSoc: best.v.nom.minSoc, maxGapH: best.v.nom.maxGapH, fails: best.v.state === 0 ? best.v.nom.fails : best.v.state === 1 ? best.v.rob.fails : [], days, st6 };
    }).sort((a, c) => c.state - a.state || (a.state ? a.i - c.i : 0) || c.minSoc - a.minSoc);
    out.landing.push({ plan, iP, iS, slip, flex, cfg, base: b.state, slipped: sl.state, alts });
  }

  // 3. Mission design: designFrontier, minArray, bisectUp and the fixes sentences of drawLab, four configs, Malapert
  const fmtKg = m => (m < 10 ? m.toFixed(1) : Math.round(m)) + ' kg', fmtW = p => Math.round(p).toLocaleString('en-US') + ' W', fmtCap = c => Math.round(c).toLocaleString('en-US') + ' Wh';
  out.design = [];
  const massOf = { wkg: 80, whkg: 160 };
  for (const [site, i0, over] of [['mala', 100, {}], ['mala', 333, { tracking: false }], ['shack', 200, { fault: { kind: 'array', day: 3 } }], ['mala', 520, { safe: true, capWh: 900 }]]) {
    const se = ser[site], cfg = Object.assign({}, base, over), F = Ana.designFrontier(se, i0, cfg, massOf, 36, 12, true), b = F.best, st = Ana.verdict(se, i0, cfg).state;
    const passR = c => Ana.mission(se, i0, c, cfg.margin, false).ok, labMass = (p, c) => p / massOf.wkg + c / massOf.whkg;
    const rec = { site, i0, cfg, state: st, caps: F.caps, rob: F.rob, nom: F.nom, best: b, pMax: F.pMax, alts: [] };
    if (b) {
      const pa = Ana.minArray(se, i0, cfg, cfg.capWh, true, F.pMax, 14), cb = Ana.bisectUp(c => passR(Object.assign({}, cfg, { capWh: c })), 10, 60000, 16);
      rec.minArrayAtCap = pa; rec.minBatteryAtArray = cb;
      rec.alts.push(pa === null ? 'Keeping the ' + fmtCap(cfg.capWh) + ' battery: no array size is enough.' : 'Keeping the ' + fmtCap(cfg.capWh) + ' battery: the array ' + (pa > cfg.peakW ? 'must grow to ' : 'could shrink to ') + fmtW(Math.ceil(pa / 5) * 5) + ' (' + (pa > cfg.peakW ? '+' : '−') + fmtKg(Math.abs(pa - cfg.peakW) / massOf.wkg) + ').');
      rec.alts.push(cb === null ? 'Keeping the ' + fmtW(cfg.peakW) + ' array: no battery size is enough.' : 'Keeping the ' + fmtW(cfg.peakW) + ' array: the battery ' + (cb > cfg.capWh ? 'must grow to ' : 'could shrink to ') + fmtCap(Math.ceil(cb / 10) * 10) + ' (' + (cb > cfg.capWh ? '+' : '−') + fmtKg(Math.abs(cb - cfg.capWh) / massOf.whkg) + ').');
      if (st < 2) { const x = Ana.bisectUp(v => passR(Object.assign({}, cfg, { loadSun: -v })), -cfg.loadSun, 0, 14); rec.maxLoad = x === null ? null : -x; rec.alts.push(x === null || -x < 1 ? 'Cutting the sunlight load alone cannot save this hardware.' : 'Keeping all hardware: cut the sunlight load from ' + fmtW(cfg.loadSun) + ' to ' + fmtW(Math.floor(-x)) + '.'); }
      rec.mass = labMass(cfg.peakW, cfg.capWh);
    } else rec.whyNone = Ana.mission(se, i0, Object.assign({}, cfg, { peakW: F.pMax, capWh: 60000 }), cfg.margin, false).fails[0] || 'the needs cannot be met';
    out.design.push(rec);
  }

  // 4. Opportunity atlas: drawAtlas's loop (120 landings every 12 h) and its four best dates at least 6 steps apart
  out.atlas = [];
  for (const [site, a0, over] of [['mala', 24, {}], ['ridge', 60, { capWh: 3000, maxGapH: 24 }]]) {
    const se = ser[site], cfg = Object.assign({}, base, over), NA = 120, m = [], pk = [], cp = [];
    for (let j = 0; j < NA; j++) { const i = a0 + j * 12; if (i + cfg.days * 24 > N) { m.push(null); pk.push(null); cp.push(null); continue; } const F = Ana.designFrontier(se, i, cfg, massOf, 12, 9, false); m.push(F.best ? F.best.mass : null); pk.push(F.best ? F.best.peakW : null); cp.push(F.best ? F.best.capWh : null); }
    const order = []; for (let j = 0; j < NA; j++) if (m[j] !== null) order.push(j); order.sort((a, b) => m[a] - m[b]);
    const top = []; for (const j of order) { if (top.every(q => Math.abs(q - j) >= 6)) top.push(j); if (top.length === 4) break; }
    out.atlas.push({ site, a0, cfg, mass: m, peakW: pk, capWh: cp, top });
  }

  // 5. DSN: Moon elevation at the three complexes, hourly for one week. Eng.dsnView (refraction 'normal', what main's
  //    status panel shows) and the same Astronomy Engine call without refraction ('airless', like Horizons and SPICE).
  const A = require('astronomy-engine'), STN = [['Goldstone', 35.4267, -116.8900], ['Madrid', 40.4314, -4.2481], ['Canberra', -35.4014, 148.9817]];
  const airless = ms => { const t = A.MakeTime(new Date(ms)); return STN.map(([name, lat, lon]) => { const obs = new A.Observer(lat, lon, 900), eq = A.Equator(A.Body.Moon, t, obs, true, true), h = A.Horizon(t, obs, eq.ra, eq.dec, null); return { name, el: h.altitude, az: h.azimuth }; }); };
  out.dsn = []; for (let hh = 0; hh < 168; hh++) out.dsn.push({ ms: T0 + hh * 3600e3, v: Eng.dsnView(T0 + hh * 3600e3), airless: airless(T0 + hh * 3600e3) });

  const dir = path.join(__dirname, '..', 'tests', 'fixtures'); fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'golden_map.bin.gz'), zlib.gzipSync(Buffer.concat(bins), { level: 9 }));
  fs.writeFileSync(path.join(dir, 'golden_phase2.json'), JSON.stringify(out));
  console.log('wrote golden_phase2.json', (JSON.stringify(out).length / 1e6).toFixed(1), 'MB and golden_map.bin.gz', (fs.statSync(path.join(dir, 'golden_map.bin.gz')).size / 1e6).toFixed(2), 'MB');
})().catch(e => { console.error(e); process.exit(1); });
